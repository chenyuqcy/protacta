import CoreGraphics
import XCTest
@testable import Protacta

final class PaperRegistrationTests: XCTestCase {
    func testRawVisionCoordinatesFlipOnceInLandscapeViewport() throws {
        // The unequal corner positions make a double flip or reflection visible
        // even after the four points have been reordered.
        let displayed = try XCTUnwrap(PaperImageCoordinates.viewportQuadrilateral(
            visionCorners: rawAsymmetricVisionCorners, displayTransform: .identity))
        assertQuad(displayed, equals: quad([CGPoint(x: 0.2, y: 0.1), CGPoint(x: 0.7, y: 0.2),
                                            CGPoint(x: 0.8, y: 0.8), CGPoint(x: 0.1, y: 0.9)]))
    }

    func testPortraitQuarterTurnAppliesAfterVisionOriginConversion() throws {
        // Normalized clockwise quarter-turn: (x,y) -> (1-y,x).
        let turn = CGAffineTransform(a: 0, b: 1, c: -1, d: 0, tx: 1, ty: 0)
        let displayed = try XCTUnwrap(PaperImageCoordinates.viewportQuadrilateral(
            visionCorners: rawAsymmetricVisionCorners, displayTransform: turn))
        assertQuad(displayed, equals: quad([CGPoint(x: 0.1, y: 0.1), CGPoint(x: 0.9, y: 0.2),
                                            CGPoint(x: 0.8, y: 0.7), CGPoint(x: 0.2, y: 0.8)]))
    }

    func testOppositeLandscapeOrientationUsesTheProvidedDisplayTransform() throws {
        let halfTurn = CGAffineTransform(a: -1, b: 0, c: 0, d: -1, tx: 1, ty: 1)
        let displayed = try XCTUnwrap(PaperImageCoordinates.viewportQuadrilateral(
            visionCorners: rawAsymmetricVisionCorners, displayTransform: halfTurn))
        assertQuad(displayed, equals: quad([CGPoint(x: 0.2, y: 0.2), CGPoint(x: 0.9, y: 0.1),
                                            CGPoint(x: 0.8, y: 0.9), CGPoint(x: 0.3, y: 0.8)]))
    }

    func testAspectFillCropMapsVisiblePaperAndRejectsClippedCorners() throws {
        let crop = CGAffineTransform(a: 2, b: 0, c: 0, d: 1, tx: -0.5, ty: 0)
        let visible = [CGPoint(x: 0.35, y: 0.9), CGPoint(x: 0.65, y: 0.9),
                       CGPoint(x: 0.65, y: 0.1), CGPoint(x: 0.35, y: 0.1)]
        let displayed = try XCTUnwrap(PaperImageCoordinates.viewportQuadrilateral(
            visionCorners: visible, displayTransform: crop))
        assertQuad(displayed, equals: quad([CGPoint(x: 0.2, y: 0.1), CGPoint(x: 0.8, y: 0.1),
                                            CGPoint(x: 0.8, y: 0.9), CGPoint(x: 0.2, y: 0.9)]))
        let clipped = [CGPoint(x: 0.24, y: 0.9), CGPoint(x: 0.65, y: 0.9),
                       CGPoint(x: 0.65, y: 0.1), CGPoint(x: 0.24, y: 0.1)]
        XCTAssertNil(PaperImageCoordinates.viewportQuadrilateral(visionCorners: clipped, displayTransform: crop),
                     "Even a corner only 2% outside the displayed view must not be clamped into an alignment")
    }

    func testCoordinateConversionRejectsInvalidRawCornersAndTransforms() {
        XCTAssertNil(PaperImageCoordinates.viewportQuadrilateral(
            visionCorners: Array(rawAsymmetricVisionCorners.prefix(3)), displayTransform: .identity))
        var invalid = rawAsymmetricVisionCorners
        invalid[0].x = -.infinity
        XCTAssertNil(PaperImageCoordinates.viewportQuadrilateral(visionCorners: invalid, displayTransform: .identity))
        invalid[0] = CGPoint(x: -0.01, y: 0.5)
        XCTAssertNil(PaperImageCoordinates.viewportQuadrilateral(visionCorners: invalid, displayTransform: .identity))
        let invalidTransform = CGAffineTransform(a: .nan, b: 0, c: 0, d: 1, tx: 0, ty: 0)
        XCTAssertNil(PaperImageCoordinates.viewportQuadrilateral(
            visionCorners: rawAsymmetricVisionCorners, displayTransform: invalidTransform))
    }

    func testIdentityAndAffineMapping() throws {
        let identity = try XCTUnwrap(PaperRegistration(quadrilateral: .unit))
        assertPoint(identity.map(CGPoint(x: 0.23, y: 0.71)), equals: CGPoint(x: 0.23, y: 0.71))

        let skewed = PaperQuadrilateral(topLeft: CGPoint(x: 0.1, y: 0.2),
                                        topRight: CGPoint(x: 0.7, y: 0.3),
                                        bottomRight: CGPoint(x: 0.8, y: 0.8),
                                        bottomLeft: CGPoint(x: 0.2, y: 0.7))
        let affine = try XCTUnwrap(PaperRegistration(quadrilateral: skewed))
        assertPoint(affine.map(CGPoint(x: 0.25, y: 0.6)), equals: CGPoint(x: 0.31, y: 0.525))
    }

    func testPerspectiveMappingAtIndependentInteriorPoints() throws {
        // This trapezoid is generated by x=(0.1+0.8u)/(1+0.4u+0.2v),
        // y=(0.2+0.6v)/(1+0.4u+0.2v). Expected interior coordinates are
        // evaluated independently; corner-only checks would miss affine warps.
        let quad = perspectiveQuadrilateral
        let registration = try XCTUnwrap(PaperRegistration(quadrilateral: quad))
        assertPoint(registration.map(CGPoint(x: 0.25, y: 0.5)), equals: CGPoint(x: 0.25, y: 5.0 / 12))
        assertPoint(registration.map(CGPoint(x: 0.75, y: 0.25)), equals: CGPoint(x: 14.0 / 27, y: 7.0 / 27))
        assertPoint(registration.map(CGPoint(x: 0.5, y: 0.5)), equals: CGPoint(x: 5.0 / 13, y: 5.0 / 13))
        for (source, target) in zip(PaperQuadrilateral.unit.points, quad.points) {
            assertPoint(registration.map(source), equals: target)
        }
    }

    func testOrderingIsIndependentOfDetectorCornerOrder() throws {
        let corners = perspectiveQuadrilateral.points
        for permutation in permutations(corners) {
            let ordered = try XCTUnwrap(PaperQuadrilateral.ordered(permutation))
            XCTAssertEqual(ordered, perspectiveQuadrilateral)
        }
        XCTAssertNil(PaperQuadrilateral.ordered(Array(corners.prefix(3))))
        XCTAssertNil(PaperQuadrilateral.ordered(corners + [CGPoint(x: 0.5, y: 0.5)]))
    }

    func testCyclicRotationPreservesLandmarkCorrespondence() throws {
        let once = PaperQuadrilateral.unit.rotated(by: 1)
        XCTAssertEqual(once.points, [CGPoint(x: 1, y: 0), CGPoint(x: 1, y: 1),
                                    CGPoint(x: 0, y: 1), CGPoint(x: 0, y: 0)])
        XCTAssertTrue(once.isValid)
        let registration = try XCTUnwrap(PaperRegistration(quadrilateral: once))
        assertPoint(registration.map(CGPoint(x: 0.2, y: 0.7)), equals: CGPoint(x: 0.3, y: 0.2))
        XCTAssertEqual(PaperQuadrilateral.unit.rotated(by: -1).rotated(by: 1), .unit)
        XCTAssertEqual(PaperQuadrilateral.unit.rotated(by: 4), .unit)
        XCTAssertEqual(PaperQuadrilateral.unit.rotated(by: Int.min), .unit)
    }

    func testExplicitReflectedCorrespondenceIsNotSilentlyReordered() throws {
        let reflected = PaperQuadrilateral(topLeft: CGPoint(x: 1, y: 0),
                                           topRight: CGPoint(x: 0, y: 0),
                                           bottomRight: CGPoint(x: 0, y: 1),
                                           bottomLeft: CGPoint(x: 1, y: 1))
        let registration = try XCTUnwrap(PaperRegistration(quadrilateral: reflected))
        assertPoint(registration.map(CGPoint(x: 0.2, y: 0.7)), equals: CGPoint(x: 0.8, y: 0.7))
    }

    func testInvalidGeometryCannotProduceRegistration() {
        let invalid = [
            quad([CGPoint(x: 0, y: 0), CGPoint(x: 0, y: 0), CGPoint(x: 1, y: 1), CGPoint(x: 0, y: 1)]),
            quad([CGPoint(x: 0, y: 0), CGPoint(x: 1, y: 1), CGPoint(x: 1, y: 0), CGPoint(x: 0, y: 1)]),
            quad([CGPoint(x: 0, y: 0), CGPoint(x: 0.3, y: 0.3), CGPoint(x: 0.6, y: 0.6), CGPoint(x: 1, y: 1)]),
            quad([CGPoint(x: 0, y: 0), CGPoint(x: 1, y: 0), CGPoint(x: 0.2, y: 0.2), CGPoint(x: 0, y: 1)]),
            quad([CGPoint(x: 0, y: 0), CGPoint(x: 0.02, y: 0), CGPoint(x: 0.02, y: 0.02), CGPoint(x: 0, y: 0.02)]),
            quad([CGPoint(x: -0.1, y: 0), CGPoint(x: 1, y: 0), CGPoint(x: 1, y: 1), CGPoint(x: 0, y: 1)]),
            quad([CGPoint(x: CGFloat.nan, y: 0), CGPoint(x: 1, y: 0), CGPoint(x: 1, y: 1), CGPoint(x: 0, y: 1)]),
            quad([CGPoint(x: 0, y: 0), CGPoint(x: CGFloat.infinity, y: 0), CGPoint(x: 1, y: 1), CGPoint(x: 0, y: 1)])
        ]
        for candidate in invalid {
            XCTAssertFalse(candidate.isValid)
            XCTAssertNil(PaperRegistration(quadrilateral: candidate))
        }
        XCTAssertNil(PaperQuadrilateral.ordered(invalid[3].points), "An interior point is not a fourth paper corner")
        XCTAssertNil(PaperQuadrilateral.ordered(invalid[6].points))
    }

    func testPerspectiveAndSmallViewportMarginDoNotRequirePhysicalAspectRatio() throws {
        let partialMargin = PaperQuadrilateral(topLeft: CGPoint(x: -0.02, y: 0.1),
                                              topRight: CGPoint(x: 0.4, y: 0.1),
                                              bottomRight: CGPoint(x: 0.4, y: 1.02),
                                              bottomLeft: CGPoint(x: -0.02, y: 1.02))
        XCTAssertTrue(partialMargin.isValid)
        let registration = try XCTUnwrap(PaperRegistration(quadrilateral: partialMargin))
        assertPoint(registration.map(CGPoint(x: 0.5, y: 0.5)), equals: CGPoint(x: 0.19, y: 0.56))
    }

    func testNonfiniteInputAndProjectiveHorizonCannotProduceVisibleCue() throws {
        let registration = try XCTUnwrap(PaperRegistration(quadrilateral: perspectiveQuadrilateral))
        XCTAssertNil(registration.map(CGPoint(x: CGFloat.nan, y: 0.5)))
        XCTAssertNil(registration.map(CGPoint(x: 0.5, y: CGFloat.infinity)))
        XCTAssertNil(registration.map(CGPoint(x: -2.5, y: 0)), "Do not emit an infinite point at the projective horizon")
    }

    private var perspectiveQuadrilateral: PaperQuadrilateral {
        PaperQuadrilateral(topLeft: CGPoint(x: 0.1, y: 0.2),
                           topRight: CGPoint(x: 9.0 / 14, y: 1.0 / 7),
                           bottomRight: CGPoint(x: 9.0 / 16, y: 0.5),
                           bottomLeft: CGPoint(x: 1.0 / 12, y: 2.0 / 3))
    }

    private var rawAsymmetricVisionCorners: [CGPoint] {
        [CGPoint(x: 0.2, y: 0.9), CGPoint(x: 0.7, y: 0.8),
         CGPoint(x: 0.8, y: 0.2), CGPoint(x: 0.1, y: 0.1)]
    }

    private func assertQuad(_ actual: PaperQuadrilateral, equals expected: PaperQuadrilateral,
                            file: StaticString = #filePath, line: UInt = #line) {
        for (actualPoint, expectedPoint) in zip(actual.points, expected.points) {
            assertPoint(actualPoint, equals: expectedPoint, file: file, line: line)
        }
    }

    private func quad(_ points: [CGPoint]) -> PaperQuadrilateral {
        PaperQuadrilateral(topLeft: points[0], topRight: points[1],
                           bottomRight: points[2], bottomLeft: points[3])
    }

    private func assertPoint(_ point: CGPoint?, equals expected: CGPoint,
                             file: StaticString = #filePath, line: UInt = #line) {
        guard let point else { XCTFail("Expected a finite mapped point", file: file, line: line); return }
        XCTAssertEqual(point.x, expected.x, accuracy: 1e-8, file: file, line: line)
        XCTAssertEqual(point.y, expected.y, accuracy: 1e-8, file: file, line: line)
    }

    private func permutations(_ points: [CGPoint]) -> [[CGPoint]] {
        guard !points.isEmpty else { return [[]] }
        return points.indices.flatMap { index -> [[CGPoint]] in
            var rest = points
            let point = rest.remove(at: index)
            return permutations(rest).map { [point] + $0 }
        }
    }
}
